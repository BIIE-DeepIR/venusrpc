"""Typed, writable model of a Hamilton liquid class.

A :class:`LiquidClassRecord` mirrors one row of the ``LiquidClass`` table in a
Hamilton liquid-class database (an MS Access ``.mdb``, e.g.
``ML_VANTAGELiquids.mdb``). Fields are pythonic ``snake_case``; each carries a
pydantic alias matching its exact DB column so the same model round-trips to
SQL without a separate mapping.

Records generated by :meth:`venusrpc.codegen.Codegen.read_liquid_classes` carry
``source_database`` (the ``.mdb`` they came from), so :meth:`LiquidClassRecord.save`
can write edits straight back:

    lc = LiquidClasses.Tip_50ulFilter_Water_DispenseSurface_Empty
    lc.as_flow_rate = 250.0
    lc.save()                      # UPDATE the source .mdb in place
    lc.save(database=other_mdb)    # or write to a different DB

``save`` upserts by class name: it UPDATEs an existing row, or INSERTs a new
one (also creating the linked ``Tadm`` row Venus requires). Venus reads the DB
live, so a saved change is picked up by the next pipetting step — no restart.

A record is also usable directly as an aspirate ``liquid_class`` argument: its
``str()`` / ``__hsl_literal__`` resolve to the class name.
"""

from __future__ import annotations

from enum import IntEnum
from pathlib import Path
from typing import Any

import pyodbc
from pydantic import BaseModel, ConfigDict, Field

from . import _hsl

# Columns we never write back: the autonumber primary key (DB-assigned) and our
# own non-DB bookkeeping field.
_PK_COLUMN = "LiquidClassID"

_ACCESS_DRIVERS = (
    "Microsoft Access Driver (*.mdb, *.accdb)",
    "Microsoft Access Driver (*.mdb)",
    "Driver do Microsoft Access (*.mdb)",
    "Microsoft Access-Treiber (*.mdb)",
)


def access_driver() -> str:
    """Return an installed MS Access ODBC driver name, or raise."""
    driver = next((d for d in _ACCESS_DRIVERS if d in pyodbc.drivers()), None)
    if driver is None:
        raise RuntimeError(
            "No Microsoft Access ODBC driver installed; install the "
            "Microsoft Access Database Engine redistributable."
        )
    return driver


def connect(database: str | Path) -> "pyodbc.Connection":
    """Open a pyodbc connection to a Hamilton liquid-class ``.mdb``."""
    return pyodbc.connect(f"Driver={{{access_driver()}}};DBQ={Path(database)};")


class DispenseMode(IntEnum):
    """Known ``DispenseMode`` values. Others may exist; the field accepts any int.

    Values verified against ML_VANTAGELiquids.mdb; names follow the Hamilton
    liquid editor's dispense-mode labels.
    """

    JET_EMPTY = 0
    JET_PART = 1
    SURFACE_EMPTY = 2
    SURFACE_PART = 3
    JET = 4  # jet / aliquot
    SURFACE = 5


class LiquidClassRecord(BaseModel):
    """One ``LiquidClass`` row, typed and writable.

    Construct from DB-column kwargs (what the generator emits) or from
    ``snake_case`` field names — both work (``populate_by_name``).
    """

    model_config = ConfigDict(populate_by_name=True, validate_assignment=True)

    # ── identity ────────────────────────────────────────────────────────────
    liquid_class_id: int | None = Field(default=None, alias="LiquidClassID")
    liquid_class_name: str = Field(alias="LiquidClassName")
    liquid_name: str = Field(default="", alias="LiquidName")
    liquid_version: str = Field(default="", alias="LiquidVersion")
    liquid_devices: str = Field(default="", alias="LiquidDevices")
    liquid_notes: bytes | None = Field(default=None, alias="LiquidNotes")
    original_liquid: int = Field(default=0, alias="OriginalLiquid")
    dispense_mode: int = Field(alias="DispenseMode")
    tip_type: int = Field(alias="TipType")
    correction_curve: bytes | None = Field(default=None, alias="CorrectionCurve")
    pressure_lld_sensitivity: int = Field(default=0, alias="PressureLLDSensitivity")
    lld_max_height_difference: float = Field(default=0.0, alias="LLDMaxHeightDifference")
    validation_state: int = Field(default=1, alias="ValidationState")
    design_history: bytes | None = Field(default=None, alias="DesignHistory")

    # ── aspirate parameters ───────────────────────────────────────────────────
    as_flow_rate: float = Field(default=0.0, alias="AsFlowRate")
    as_mix_flow_rate: float = Field(default=0.0, alias="AsMixFlowRate")
    as_air_transport_volume: float = Field(default=0.0, alias="AsAirTransportVolume")
    as_blow_out_volume: float = Field(default=0.0, alias="AsBlowOutVolume")
    as_swap_speed: float = Field(default=0.0, alias="AsSwapSpeed")
    as_settling_time: float = Field(default=0.0, alias="AsSettlingTime")
    as_over_aspirate_volume: float = Field(default=0.0, alias="AsOverAspirateVolume")
    as_clot_retract_height: float = Field(default=0.0, alias="AsClotRetractHeight")

    # ── dispense parameters ───────────────────────────────────────────────────
    ds_flow_rate: float = Field(default=0.0, alias="DsFlowRate")
    ds_mix_flow_rate: float = Field(default=0.0, alias="DsMixFlowRate")
    ds_air_transport_volume: float = Field(default=0.0, alias="DsAirTransportVolume")
    ds_blow_out_volume: float = Field(default=0.0, alias="DsBlowOutVolume")
    ds_swap_speed: float = Field(default=0.0, alias="DsSwapSpeed")
    ds_settling_time: float = Field(default=0.0, alias="DsSettlingTime")
    ds_stop_flow_rate: float = Field(default=0.0, alias="DsStopFlowRate")
    ds_stop_back_volume: float = Field(default=0.0, alias="DsStopBackVolume")

    # ── misc ──────────────────────────────────────────────────────────────────
    whi_pip_json: str | None = Field(default=None, alias="WhiPipJson")
    # Hamilton computes CheckSum; we do not. Preserved on round-trip, left as-is
    # on edit. Real hardware may reject a stale checksum — see save() docstring.
    checksum: int | None = Field(default=None, alias="CheckSum")

    # Not a DB column: the .mdb this record was generated from / should save to.
    source_database: str | None = Field(default=None, exclude=True, repr=False)

    # ── usable as an aspirate liquid_class argument ───────────────────────────
    def __str__(self) -> str:
        return self.liquid_class_name

    def __hsl_literal__(self) -> str:
        return _hsl.string_literal(self.liquid_class_name)

    # ── persistence ───────────────────────────────────────────────────────────
    def _db_columns(self, *, exclude_none: bool) -> dict[str, Any]:
        """DB-column → value mapping, minus the PK and the bookkeeping field."""
        data = self.model_dump(by_alias=True, exclude_none=exclude_none)
        data.pop(_PK_COLUMN, None)  # PK is DB-assigned / matched via WHERE
        return data

    def save(self, database: str | Path | None = None) -> "LiquidClassRecord":
        """Write this record to the liquid-class DB (upsert by class name).

        Uses ``database`` if given, else the record's ``source_database``.
        UPDATEs the existing row with the same ``liquid_class_name``; if none
        exists, INSERTs a new row and creates its linked ``Tadm`` row (without
        which Venus aspirate fails with "TADM data for liquid class not found").

        ``None``-valued fields are not written, so a partial/hand-built record
        will not clobber existing columns with NULL. On INSERT, ``liquid_class_id``
        is set from the new autonumber id.

        Note: ``CheckSum`` is NOT recomputed. Venus reads the class live and
        simulation accepts it, but real hardware may validate the checksum;
        re-save from the Hamilton liquid editor if a run rejects an edited class.
        """
        db = database if database is not None else self.source_database
        if db is None:
            raise ValueError(
                "no database given and record has no source_database; "
                "call save(database=...)"
            )
        conn = connect(db)
        try:
            cur = conn.cursor()
            name = self.liquid_class_name
            cur.execute(
                "SELECT LiquidClassID FROM LiquidClass WHERE LiquidClassName=?", name
            )
            existing = cur.fetchone()
            data = self._db_columns(exclude_none=True)

            if existing is not None:
                self.liquid_class_id = existing[0]
                set_cols = [c for c in data if c != "LiquidClassName"]
                if set_cols:
                    assignments = ", ".join(f"{c}=?" for c in set_cols)
                    cur.execute(
                        f"UPDATE LiquidClass SET {assignments} WHERE LiquidClassName=?",
                        *[data[c] for c in set_cols],
                        name,
                    )
            else:
                cols = list(data)
                placeholders = ", ".join(["?"] * len(cols))
                cur.execute(
                    f"INSERT INTO LiquidClass ({', '.join(cols)}) "
                    f"VALUES ({placeholders})",
                    *[data[c] for c in cols],
                )
                cur.execute("SELECT @@IDENTITY")
                new_id = cur.fetchone()[0]
                self.liquid_class_id = new_id
                # Linked Tadm row is mandatory for aspirate.
                cur.execute(
                    "SELECT COUNT(*) FROM Tadm WHERE LiquidClassID=?", new_id
                )
                if cur.fetchone()[0] == 0:
                    cur.execute(
                        "INSERT INTO Tadm (LiquidClassID, TADMEnabled, CheckSum) "
                        "VALUES (?, ?, ?)",
                        new_id,
                        0,
                        0,
                    )
            conn.commit()
        finally:
            conn.close()
        return self

    # Alias requested by callers who think "write" rather than "save".
    def write(self, database: str | Path | None = None) -> "LiquidClassRecord":
        """Alias for :meth:`save`."""
        return self.save(database)

    def delete(self, database: str | Path | None = None) -> None:
        """Delete this class (and its linked ``Tadm`` rows) from the DB by name."""
        db = database if database is not None else self.source_database
        if db is None:
            raise ValueError("no database given and record has no source_database")
        conn = connect(db)
        try:
            cur = conn.cursor()
            cur.execute(
                "DELETE FROM Tadm WHERE LiquidClassID IN "
                "(SELECT LiquidClassID FROM LiquidClass WHERE LiquidClassName=?)",
                self.liquid_class_name,
            )
            cur.execute(
                "DELETE FROM LiquidClass WHERE LiquidClassName=?",
                self.liquid_class_name,
            )
            conn.commit()
        finally:
            conn.close()

    @classmethod
    def load(
        cls, name: str, database: str | Path
    ) -> "LiquidClassRecord | None":
        """Read a class by name from ``database``; ``None`` if absent."""
        conn = connect(database)
        try:
            cur = conn.cursor()
            cur.execute("SELECT * FROM LiquidClass WHERE LiquidClassName=?", name)
            row = cur.fetchone()
            if row is None:
                return None
            columns = [c[0] for c in cur.description]
            data = dict(zip(columns, row))
            return cls(**data, source_database=str(database))
        finally:
            conn.close()
